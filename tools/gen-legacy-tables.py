#!/usr/bin/env python3
"""Generates the constant tables of the block ciphers in RecursiveAI.OneCrypto.Primitives.

CAST5 S-boxes S1 to S8 are read from Appendix A of RFC 2144, the Camellia S-box from section 2.4.1 of RFC 3713 (give the
local copies of the RFC texts as arguments), (the Blowfish pi tables are generated by tools/gen-blowfish-tables.py).

usage: gen-legacy-tables.py rfc2144.txt rfc3713.txt OUTPUT_DIR
"""
import re
import sys


def rows(words, per_row, fmt):
    out = []
    for i in range(0, len(words), per_row):
        out.append("        " + ", ".join(fmt % w for w in words[i:i + per_row]) + ",")
    return "\n".join(out)


def cast5_boxes(path):
    text = open(path, encoding="ascii").read()
    text = text[text.index("Appendix A. S-Boxes"):text.index("Appendix B. Test Vectors")]
    boxes = []
    for n in range(1, 9):
        start = text.index("S-Box S%d" % n)
        end = text.index("S-Box S%d" % (n + 1)) if n < 8 else len(text)
        words = re.findall(r"\b[0-9a-f]{8}\b", text[start:end])
        assert len(words) == 256, (n, len(words))
        boxes.append([int(w, 16) for w in words])
    return boxes


def camellia_sbox1(path):
    text = open(path, encoding="ascii").read()
    start = text.index("SBOX1:\n")
    end = text.index("2.4.2.", start)
    values = []
    for line in text[start:end].splitlines():
        m = re.match(r"\s*([0-9a-f]0):((?:\s+\d+){16})\s*$", line)
        if m:
            values += [int(v) for v in m.group(2).split()]
    assert len(values) == 256
    return values


def main():
    rfc2144, rfc3713, out = sys.argv[1:4]
    header = "// <auto-generated> by tools/gen-legacy-tables.py; do not edit. </auto-generated>\n\nnamespace RecursiveAI.OneCrypto.Primitives.Internal;\n\n"

    boxes = cast5_boxes(rfc2144)
    with open(out + "/Cast5Tables.cs", "w", encoding="ascii", newline="\n") as f:
        f.write(header)
        f.write("/// <summary>The CAST5 S-boxes S1 to S8 (RFC 2144 Appendix A, Copyright (c) The Internet Society 1997), eight boxes of 256 words in order.</summary>\n")
        f.write("internal static class Cast5Tables\n{\n    internal static ReadOnlySpan<uint> SBoxes =>\n    [\n")
        f.write(rows([w for b in boxes for w in b], 6, "0x%08X"))
        f.write("\n    ];\n}\n")

    sbox = camellia_sbox1(rfc3713)
    with open(out + "/CamelliaTables.cs", "w", encoding="ascii", newline="\n") as f:
        f.write(header)
        f.write("/// <summary>The Camellia SBOX1 (RFC 3713 section 2.4.1, Copyright (c) The Internet Society 2004).</summary>\n")
        f.write("internal static class CamelliaTables\n{\n    internal static ReadOnlySpan<byte> SBox1 =>\n    [\n")
        f.write(rows(sbox, 12, "0x%02X"))
        f.write("\n    ];\n}\n")


main()
