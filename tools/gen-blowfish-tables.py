#!/usr/bin/env python3
"""Writes src/OneCrypto/Primitives/Internal/BlowfishTables.cs.

Blowfish (Schneier, 1993) initialises its 18-word P-array and four 256-word S-boxes with the hexadecimal digits of the
fractional part of pi, in that order. This computes those digits with Machin's formula in integer arithmetic, so the
table is derived from the definition rather than copied from anywhere.
"""
import sys

WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 128  # guard bits


def arctan_inv(x, one):
    # arctan(1/x) scaled by `one`
    term = one // x
    total = term
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        n += 2
        total += sign * (term // n)
        sign = -sign
    return total


one = 1 << (BITS + 64)
pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
frac = (pi - 3 * one) >> 64  # fractional part scaled by 2^BITS
words = [(frac >> (BITS - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, "pi digits are wrong"

out = []
out.append("// <auto-generated> by tools/gen-blowfish-tables.py: the fractional hexadecimal digits of pi. </auto-generated>")
out.append("")
out.append("namespace RecursiveAI.OneCrypto.Primitives.Internal;")
out.append("")
out.append("internal static class BlowfishTables")
out.append("{")
out.append("    /// <summary>The initial P-array (18 words) followed by the four S-boxes (4 x 256 words).</summary>")
out.append("    internal static ReadOnlySpan<uint> Initial =>")
out.append("    [")
for i in range(0, WORDS, 6):
    out.append("        " + ", ".join("0x%08X" % w for w in words[i:i + 6]) + ",")
out.append("    ];")
out.append("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
